#!/usr/bin/env python3
"""Render the technical Markdown sources for buildless GitHub Pages.

Install scripts/requirements-docs.txt, then run this script from any directory.
Use --check to verify the committed HTML matches its Markdown sources.
"""

import argparse
from html import escape
from pathlib import Path
import re
import sys

import markdown


ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
REPO = "https://github.com/ZMC66666/3d-garment-part-understanding"
PAGES = (
    ("alignment_method", "Alignment Method", "How garment semantics, structural fields, and body anatomy define compatible surface correspondences and hem clearance."),
    ("evaluation_protocol", "Evaluation Protocol", "Prediction-driven Table 3 settings, shared evaluation regions, metric definitions, and aggregation."),
)


def render(slug, title, description):
    source = (DOCS / f"{slug}.md").read_text(encoding="utf-8")
    source = re.sub(r"\A# [^\n]+\n", "", source, count=1)
    math = []

    def protect(match):
        token = f"MATHPLACEHOLDER{len(math):04d}END"
        math.append((token, match.group(0)))
        return token

    # Preserve TeX before Markdown interprets backslashes, underscores, or pipes.
    source = re.sub(r"\$\$[\s\S]*?\$\$|(?<!\$)\$(?!\$)[^\n$]+\$", protect, source)
    converter = markdown.Markdown(extensions=["tables", "fenced_code", "toc"],
                                  extension_configs={"toc": {"permalink": "#"}})
    body = converter.convert(source)
    for token, tex in math:
        value = escape(tex)
        if tex.startswith("$$"):
            # Display tokens occupy their own paragraph in the Markdown source.
            body = body.replace(f"<p>{token}</p>", f'<div class="math-display">{value}</div>')
        body = body.replace(token, value)
    body = body.replace("<table>", '<div class="table-scroll"><table>').replace("</table>", "</table></div>")

    def local_link(match):
        target, fragment = match.groups()
        if target in {item[0] for item in PAGES}:
            return f'href="{target}.html{fragment or ""}"'
        return f'href="{REPO}/blob/main/docs/{target}.md{fragment or ""}"'

    body = re.sub(r'href="([a-z_]+)\.md(#[^"]*)?"', local_link, body)
    nav = []
    for page, label, _ in PAGES:
        current = ' aria-current="page"' if page == slug else ""
        nav.append(f'<a href="{page}.html"{current}>{label}</a>')
    return f'''<!doctype html>
<!-- Generated by scripts/build_technical_docs.py. Edit {slug}.md instead. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="{escape(description, quote=True)}">
  <title>{escape(title)} · 3D Garment Part Understanding</title>
  <link rel="stylesheet" href="technical.css">
  <script>
    window.MathJax = {{
      tex: {{inlineMath: [['$', '$'], ['\\\\(', '\\\\)']], displayMath: [['$$', '$$']]}},
      options: {{skipHtmlTags: ['script', 'noscript', 'style', 'textarea', 'pre', 'code']}}
    }};
  </script>
  <script defer src="https://cdn.jsdelivr.net/npm/mathjax@3.2.2/es5/tex-chtml.js"></script>
</head>
<body>
  <a class="skip-link" href="#content">Skip to content</a>
  <header class="site-bar">
    <div class="bar-inner">
      <a class="brand" href="index.html#technical-details">← 3D Garment Part Understanding</a>
      <nav class="doc-nav" aria-label="Technical documents">{"".join(nav)}</nav>
    </div>
  </header>
  <div class="doc-hero">
    <div class="hero-inner">
      <p class="eyebrow">Technical supplement</p>
      <h1>{escape(title)}</h1>
      <p class="intro">{escape(description)}</p>
      <div class="hero-meta">
        <a href="{REPO}/blob/main/docs/{slug}.md">View Markdown source ↗</a>
      </div>
    </div>
  </div>
  <div class="doc-layout">
    <aside class="doc-sidebar" aria-label="Page contents">
      <details open><summary>On this page</summary>{converter.toc}</details>
    </aside>
    <main id="content" class="doc-content" tabindex="-1">{body}</main>
  </div>
  <footer class="doc-footer">
    <a href="index.html#technical-details">Project overview</a>
    <a href="{REPO}">GitHub repository</a>
    <p>3D Garment Part Understanding · Method and evaluation details</p>
  </footer>
</body>
</html>
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for slug, title, description in PAGES:
        output = render(slug, title, description)
        target = DOCS / f"{slug}.html"
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != output:
                stale.append(target.name)
        else:
            target.write_text(output, encoding="utf-8")
            print(f"Rendered {target.name}")
    # Keep the previous public field-usage URL working after merging the text.
    redirect = '''<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta http-equiv="refresh" content="0;url=alignment_method.html#2-structural-fields-from-supervision-to-alignment">
  <link rel="canonical" href="alignment_method.html">
  <title>Structural Fields · Alignment Method</title>
  <link rel="stylesheet" href="technical.css">
</head>
<body>
  <main class="hero-inner">
    <h1>Structural Fields in Alignment</h1>
    <p><a href="alignment_method.html#2-structural-fields-from-supervision-to-alignment">Continue to the alignment method</a>, which includes the structural-field explanation.</p>
  </main>
</body>
</html>
'''
    redirect_path = DOCS / "structural_field_usage.html"
    if args.check:
        if not redirect_path.exists() or redirect_path.read_text(encoding="utf-8") != redirect:
            stale.append(redirect_path.name)
    else:
        redirect_path.write_text(redirect, encoding="utf-8")
        print(f"Rendered {redirect_path.name} redirect")
    if stale:
        print("Regenerate technical pages: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
